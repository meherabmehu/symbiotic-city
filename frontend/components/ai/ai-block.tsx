"use client";

/**
 * Shared presentation for AI feature replies.
 *
 * The provider chip is the load-bearing part: it renders whatever the API
 * said produced the text -- "LLM (Groq)" versus the rule-based fallback -- so
 * a screenshot of any answer shows what actually answered. Citations are
 * links to the entities that were fed to the model, and every reply body goes
 * through one secure Markdown renderer.
 */

import Link from "next/link";
import { useState, type ReactNode } from "react";
import { AlertTriangle, BookOpenText, Info, Loader2, Sparkles } from "lucide-react";
import ReactMarkdown, { defaultUrlTransform } from "react-markdown";
import remarkGfm from "remark-gfm";
import { api } from "@/lib/api";
import {
  buildCitationViews,
  occurrenceText,
  type AiCitationLike,
} from "@/lib/ai-citations";

export type AiCitation = AiCitationLike;

export interface AiReplyPayload {
  /** Most features answer with `reply`; the resilience report uses `report`. */
  reply?: string | null;
  report?: string;
  provider: string;
  /** True when the model's answer was cut off and discarded. */
  truncated?: boolean;
  /** Why a deterministic fallback answered, when the reason is not "no key". */
  notice?: string | null;
  citations?: AiCitation[];
}

/** The text to render: `reply` when present, `report` for the report endpoint. */
export function replyText(payload: AiReplyPayload): string {
  return payload.reply ?? payload.report ?? "";
}

export function ProviderChip({ provider }: { provider: string }) {
  const llm = provider.startsWith("LLM");
  return (
    <span
      data-testid="ai-provider"
      className={
        llm
          ? "inline-flex items-center gap-1 rounded-full border border-accent/40 bg-accent/10 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider text-accent"
          : "inline-flex items-center gap-1 rounded-full border border-amber/40 bg-amber/10 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider text-amber"
      }
      title={
        llm
          ? "Generated by the configured Groq model"
          : provider.includes("no LLM key")
            ? "Deterministic fallback — no LLM key is configured"
            : "Deterministic fallback — the model response was unavailable or incomplete"
      }
    >
      {llm ? <Sparkles className="h-3 w-3" aria-hidden /> : <BookOpenText className="h-3 w-3" aria-hidden />}
      {provider}
    </span>
  );
}

/**
 * Why a fallback answered. Shown next to the provider chip so an operator never
 * reads a truncated or rejected model draft as the model's complete answer.
 */
export function AiNotice({ message }: { message: string }) {
  return (
    <p
      data-testid="ai-notice"
      role="status"
      className="mt-2 flex items-start gap-2 rounded-lg border border-amber/30 bg-amber/10 p-2.5 text-[11px] leading-relaxed text-amber"
    >
      <Info className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
      <span>{message}</span>
    </p>
  );
}

export function AiCitations({ citations }: { citations: AiCitation[] }) {
  const views = buildCitationViews(citations);
  if (views.length === 0) return null;
  return (
    <ul className="mt-3 flex flex-wrap gap-1.5" aria-label="Cited entities">
      {views.map((view) => {
        const marker = occurrenceText(view);
        const inner = (
          <>
            <span className="uppercase tracking-wider text-ink-500">{view.typeLabel}</span>
            <span className="text-ink-200">{view.label}</span>
            {marker ? (
              <span className="rounded bg-white/10 px-1 py-0.5 font-mono text-[10px] text-ink-300">
                {marker}
              </span>
            ) : null}
            {view.detail ? (
              <span className="text-ink-500">{view.detail}</span>
            ) : null}
          </>
        );
        const linkClass =
          "inline-flex max-w-full items-center gap-1.5 rounded-lg border border-white/10 bg-white/[0.04] px-2 py-1 text-[11px] transition hover:border-accent/40 hover:text-white";
        return (
          <li key={view.key}>
            {view.href ? (
              <Link href={view.href} className={linkClass}>
                {inner}
              </Link>
            ) : (
              <span className={linkClass}>{inner}</span>
            )}
          </li>
        );
      })}
    </ul>
  );
}

/**
 * Only same-origin application paths and ordinary web links survive; every
 * other scheme (javascript:, data:, vbscript:) is stripped by the default
 * transform.
 */
function safeMarkdownUrl(url: string): string {
  if (url.startsWith("/") && !url.startsWith("//")) return url;
  return defaultUrlTransform(url);
}

function isExternal(href: string | undefined): boolean {
  return Boolean(href && /^https?:\/\//i.test(href));
}

/** Secure shared renderer for model and deterministic Markdown replies. */
export function AiMarkdown({ children }: { children: string }) {
  // Models sometimes emit a literal "<br>" inside a line; skipHtml drops it as
  // markup, so turning it into a line break keeps the intended layout.
  const markdown = children.replace(/<br\s*\/?>/gi, "\n");
  return (
    <div className="ai-markdown mt-2 max-w-full overflow-x-hidden text-sm leading-relaxed text-ink-200">
      <ReactMarkdown
        remarkPlugins={[remarkGfm]}
        skipHtml
        urlTransform={safeMarkdownUrl}
        components={{
          h1: ({ children }) => <h2 className="mb-2 mt-4 text-lg font-semibold text-white">{children}</h2>,
          h2: ({ children }) => <h3 className="mb-2 mt-4 text-base font-semibold text-white">{children}</h3>,
          h3: ({ children }) => <h4 className="mb-1.5 mt-3 font-semibold text-white">{children}</h4>,
          h4: ({ children }) => <h5 className="mb-1.5 mt-3 text-sm font-semibold text-white">{children}</h5>,
          p: ({ children }) => <p className="my-2 break-words">{children}</p>,
          ul: ({ children }) => <ul className="my-2 list-disc space-y-1 pl-5">{children}</ul>,
          ol: ({ children }) => <ol className="my-2 list-decimal space-y-1 pl-5">{children}</ol>,
          li: ({ children }) => <li className="break-words">{children}</li>,
          blockquote: ({ children }) => (
            <blockquote className="my-2 border-l-2 border-accent/40 pl-3 text-ink-300">{children}</blockquote>
          ),
          hr: () => <hr className="my-4 border-white/10" />,
          table: ({ children }) => (
            <div className="my-3 max-w-full overflow-x-auto">
              <table className="w-full border-collapse text-left text-xs">{children}</table>
            </div>
          ),
          th: ({ children }) => (
            <th className="border border-white/15 bg-white/[0.06] px-2 py-1.5 font-semibold text-white">{children}</th>
          ),
          td: ({ children }) => <td className="border border-white/10 px-2 py-1.5 align-top">{children}</td>,
          pre: ({ children }) => (
            <pre className="my-3 max-w-full overflow-x-auto rounded-lg border border-white/10 bg-navy-950/80 p-3 text-xs leading-relaxed">
              {children}
            </pre>
          ),
          code: ({ className, children }) => {
            const block = Boolean(className && className.includes("language-"));
            if (block) {
              return <code className="font-mono text-[0.9em] text-cyan-200">{children}</code>;
            }
            return (
              <code className="rounded bg-white/10 px-1 py-0.5 font-mono text-[0.9em] text-cyan-200">
                {children}
              </code>
            );
          },
          // Images are blocked outright: a model-supplied URL is an outbound
          // request the operator never asked for (and a tracking pixel).
          img: () => null,
          a: ({ children, href }) =>
            isExternal(href) ? (
              <a
                href={href}
                target="_blank"
                rel="noreferrer noopener nofollow"
                className="text-accent underline decoration-accent/50 underline-offset-2 hover:text-white"
              >
                {children}
              </a>
            ) : (
              <a
                href={href}
                rel="noreferrer noopener"
                className="text-accent underline decoration-accent/50 underline-offset-2 hover:text-white"
              >
                {children}
              </a>
            ),
        }}
      >
        {markdown}
      </ReactMarkdown>
    </div>
  );
}

export function AiReplyCard({
  reply,
  provider,
  citations,
  notice,
  footer,
}: {
  reply: string;
  provider: string;
  citations?: AiCitation[];
  notice?: string | null;
  footer?: ReactNode;
}) {
  return (
    <div className="mt-3 rounded-xl border border-white/10 bg-navy-950/60 p-3" data-testid="ai-reply">
      <div className="flex flex-wrap items-center gap-2">
        <ProviderChip provider={provider} />
      </div>
      {notice ? <AiNotice message={notice} /> : null}
      <AiMarkdown>{reply}</AiMarkdown>
      {citations ? <AiCitations citations={citations} /> : null}
      {footer}
    </div>
  );
}

/**
 * One-shot POST helper for the AI endpoints: remembers the last reply,
 * surfaces API failures as text, and never throws at the call site.
 */
export function useAiCall<T extends AiReplyPayload>() {
  const [result, setResult] = useState<T | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  async function run(path: string, body: unknown = {}): Promise<T | null> {
    setLoading(true);
    setError(null);
    try {
      const data = await api.post<T>(path, body);
      setResult(data);
      return data;
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "The assistant is unavailable.");
      return null;
    } finally {
      setLoading(false);
    }
  }

  return { run, result, error, loading };
}

export function AiError({ message }: { message: string }) {
  return (
    <p className="mt-3 flex items-start gap-2 rounded-lg border border-coral/30 bg-coral/10 p-2.5 text-xs text-coral" role="alert">
      <AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
      {message}
    </p>
  );
}

export function AiLoading({ label }: { label: string }) {
  return (
    <p className="mt-3 flex items-center gap-2 text-xs text-ink-400" role="status">
      <Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden />
      {label}
    </p>
  );
}
