"use client";

/**
 * Shared presentation for AI feature replies.
 *
 * The provider chip is the load-bearing part: it renders whatever the API
 * said produced the text -- "LLM (Groq)" versus the rule-based fallback --
 * so a screenshot of any answer shows what actually answered. Citations are
 * links to the entities that were fed to the model, not decoration.
 */

import Link from "next/link";
import { useState, type ReactNode } from "react";
import { AlertTriangle, BookOpenText, Loader2, Sparkles } from "lucide-react";
import { api } from "@/lib/api";

export interface AiCitation {
  entity_type: string;
  entity_id: string | number;
  label: string;
  snippet?: string;
}

export interface AiReplyPayload {
  /** Most features answer with `reply`; the resilience report uses `report`. */
  reply?: string | null;
  report?: string;
  provider: string;
  citations?: AiCitation[];
}

/** The text to render: `reply` when present, `report` for the report endpoint. */
export function replyText(payload: AiReplyPayload): string {
  return payload.reply ?? payload.report ?? "";
}

const CITATION_HREF: Record<string, (id: string | number) => string> = {
  asset: (id) => `/infrastructure/${id}`,
  incident: (id) => `/incidents/${id}`,
  task: (id) => `/tasks/${id}`,
  optimization_plan: (id) => `/optimization/plans/${id}`,
};

export function ProviderChip({ provider }: { provider: string }) {
  const llm = provider.startsWith("LLM");
  return (
    <span
      data-testid="ai-provider"
      className={
        llm
          ? "inline-flex items-center gap-1 rounded-full border border-accent/40 bg-accent/10 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider text-accent"
          : "inline-flex items-center gap-1 rounded-full border border-amber/40 bg-amber/10 px-2 py-0.5 text-[10px] font-semibold uppercase tracking-wider text-amber"
      }
      title={
        llm
          ? "Generated by the configured Groq model"
          : "Deterministic fallback -- no LLM key is configured"
      }
    >
      {llm ? <Sparkles className="h-3 w-3" aria-hidden /> : <BookOpenText className="h-3 w-3" aria-hidden />}
      {provider}
    </span>
  );
}

export function AiCitations({ citations }: { citations: AiCitation[] }) {
  if (citations.length === 0) return null;
  return (
    <ul className="mt-3 flex flex-wrap gap-1.5" aria-label="Cited entities">
      {citations.map((citation) => {
        const href = CITATION_HREF[citation.entity_type]?.(citation.entity_id);
        const inner = (
          <>
            <span className="uppercase text-ink-500">{citation.entity_type}</span>
            <span className="text-ink-200">{citation.label}</span>
          </>
        );
        return (
          <li key={`${citation.entity_type}-${citation.entity_id}`}>
            {href ? (
              <Link
                href={href}
                className="inline-flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/[0.04] px-2 py-1 text-[11px] transition hover:border-accent/40 hover:text-white"
              >
                {inner}
              </Link>
            ) : (
              <span className="inline-flex items-center gap-1.5 rounded-lg border border-white/10 bg-white/[0.04] px-2 py-1 text-[11px]">
                {inner}
              </span>
            )}
          </li>
        );
      })}
    </ul>
  );
}

export function AiReplyCard({
  reply,
  provider,
  citations,
  footer,
}: {
  reply: string;
  provider: string;
  citations?: AiCitation[];
  footer?: ReactNode;
}) {
  return (
    <div className="mt-3 rounded-xl border border-white/10 bg-navy-950/60 p-3" data-testid="ai-reply">
      <div className="flex flex-wrap items-center gap-2">
        <ProviderChip provider={provider} />
      </div>
      {/* Whitespace preserved: the rule-based fallbacks use line breaks. */}
      <p className="mt-2 whitespace-pre-wrap text-sm leading-relaxed text-ink-200">{reply}</p>
      {citations ? <AiCitations citations={citations} /> : null}
      {footer}
    </div>
  );
}

/**
 * One-shot POST helper for the AI endpoints: remembers the last reply,
 * surfaces API failures as text, and never throws at the call site.
 */
export function useAiCall<T extends AiReplyPayload>() {
  const [result, setResult] = useState<T | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);

  async function run(path: string, body: unknown = {}): Promise<T | null> {
    setLoading(true);
    setError(null);
    try {
      const data = await api.post<T>(path, body);
      setResult(data);
      return data;
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "The assistant is unavailable.");
      return null;
    } finally {
      setLoading(false);
    }
  }

  return { run, result, error, loading };
}

export function AiError({ message }: { message: string }) {
  return (
    <p className="mt-3 flex items-start gap-2 rounded-lg border border-coral/30 bg-coral/10 p-2.5 text-xs text-coral" role="alert">
      <AlertTriangle className="mt-0.5 h-3.5 w-3.5 shrink-0" aria-hidden />
      {message}
    </p>
  );
}

export function AiLoading({ label }: { label: string }) {
  return (
    <p className="mt-3 flex items-center gap-2 text-xs text-ink-400" role="status">
      <Loader2 className="h-3.5 w-3.5 animate-spin" aria-hidden />
      {label}
    </p>
  );
}
