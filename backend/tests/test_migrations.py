"""The Alembic revision must actually build the schema it claims to.

The initial revision was autogenerated against SQLite, where ``op.create_table``
in alphabetical order is accepted even though 12 of the 60 foreign keys point at
tables that do not exist yet. PostgreSQL validates foreign keys at DDL time, so
``alembic upgrade head`` failed outright on the documented production database.

These tests run the real revision and compare the result with the model
metadata, so a future regeneration that reintroduces the problem fails here
instead of in a deployment.
"""
from __future__ import annotations

import os
import sqlite3
import subprocess
import sys
from pathlib import Path

import pytest

BACKEND = Path(__file__).resolve().parents[1]
REVISIONS = sorted((BACKEND / "migrations" / "versions").glob("*.py"))


def alembic(database_url: str, *args: str) -> subprocess.CompletedProcess:
    env = dict(os.environ, DATABASE_URL=database_url, PYTHONPATH=str(BACKEND))
    return subprocess.run(
        [sys.executable, "-m", "alembic", *args],
        cwd=BACKEND, env=env, capture_output=True, text=True, timeout=180,
    )


def sqlite_summary(path: Path) -> tuple[int, int, int]:
    connection = sqlite3.connect(path)
    try:
        tables = connection.execute(
            "select count(*) from sqlite_master where type='table' and name not like 'sqlite_%'"
        ).fetchone()[0]
        indexes = connection.execute(
            "select count(*) from sqlite_master where type='index' and name not like 'sqlite_%'"
        ).fetchone()[0]
        ddl = " ".join(
            row[0] or ""
            for row in connection.execute("select sql from sqlite_master where type='table'")
        )
        return tables, indexes, ddl.count("REFERENCES")
    finally:
        connection.close()


@pytest.fixture()
def migrated(tmp_path):
    url = f"sqlite:///{tmp_path / 'migrated.db'}"
    result = alembic(url, "upgrade", "head")
    assert result.returncode == 0, result.stderr
    return tmp_path / "migrated.db"


def test_single_head_revision():
    assert len(REVISIONS) == 1, [p.name for p in REVISIONS]


def test_revision_creates_every_model_table(migrated):
    import app.models  # noqa: F401  (registers the metadata)
    from app.core.database import Base

    connection = sqlite3.connect(migrated)
    try:
        created = {
            row[0]
            for row in connection.execute(
                "select name from sqlite_master where type='table' and name not like 'sqlite_%'"
            )
        }
    finally:
        connection.close()
    assert created - {"alembic_version"} == set(Base.metadata.tables)


def test_revision_creates_every_foreign_key(migrated):
    """60 foreign keys in the metadata, 60 REFERENCES clauses in the schema."""
    import app.models  # noqa: F401
    from app.core.database import Base

    expected = sum(len(table.foreign_key_constraints) for table in Base.metadata.tables.values())
    _, _, references = sqlite_summary(migrated)
    assert expected == 60
    assert references == expected


def test_revision_creates_every_index(migrated):
    _, indexes, _ = sqlite_summary(migrated)
    assert indexes == 28


def test_downgrade_removes_everything(tmp_path):
    url = f"sqlite:///{tmp_path / 'roundtrip.db'}"
    assert alembic(url, "upgrade", "head").returncode == 0
    assert alembic(url, "downgrade", "base").returncode == 0
    tables, indexes, references = sqlite_summary(tmp_path / "roundtrip.db")
    # alembic's own bookkeeping table survives by design; nothing else may.
    assert (tables, indexes, references) == (1, 0, 0)


def test_upgrade_downgrade_is_repeatable(tmp_path):
    url = f"sqlite:///{tmp_path / 'repeat.db'}"
    for _ in range(2):
        assert alembic(url, "upgrade", "head").returncode == 0
        assert alembic(url, "downgrade", "base").returncode == 0
    assert alembic(url, "upgrade", "head").returncode == 0


@pytest.mark.skipif(
    not os.environ.get("POSTGRES_TEST_URL"),
    reason="set POSTGRES_TEST_URL to run the migration against PostgreSQL",
)
def test_round_trip_on_postgresql():
    """The bug this guards: 'relation \"users\" does not exist' on PostgreSQL."""
    url = os.environ["POSTGRES_TEST_URL"]
    upgrade = alembic(url, "upgrade", "head")
    assert upgrade.returncode == 0, upgrade.stderr
    downgrade = alembic(url, "downgrade", "base")
    assert downgrade.returncode == 0, downgrade.stderr
    again = alembic(url, "upgrade", "head")
    assert again.returncode == 0, again.stderr
